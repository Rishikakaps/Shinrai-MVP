-- POC physical schema: typed JSONB entities plus an ordered immutable event ledger.
-- A private schema avoids exposing application rows through Supabase's public Data API.
CREATE SCHEMA IF NOT EXISTS cdi;
CREATE TABLE IF NOT EXISTS cdi.objects (
 sequence BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 id TEXT PRIMARY KEY, kind TEXT NOT NULL, inspection_id TEXT NOT NULL,
 version INTEGER NOT NULL CHECK (version > 0), data JSONB NOT NULL
);
CREATE INDEX IF NOT EXISTS objects_scope ON cdi.objects(inspection_id,kind,sequence);
CREATE TABLE IF NOT EXISTS cdi.review_events (
 sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id TEXT UNIQUE NOT NULL, inspection_id TEXT NOT NULL, entity_id TEXT NOT NULL,
 data JSONB NOT NULL
);
CREATE INDEX IF NOT EXISTS events_scope ON cdi.review_events(inspection_id,sequence);
CREATE OR REPLACE FUNCTION cdi.reject_event_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
 RAISE EXCEPTION 'Review events are immutable';
END;
$$;
DO $$
BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_trigger
                WHERE tgrelid='cdi.review_events'::regclass AND tgname='immutable_event_mutation') THEN
  CREATE TRIGGER immutable_event_mutation BEFORE UPDATE OR DELETE OR TRUNCATE
  ON cdi.review_events FOR EACH STATEMENT EXECUTE FUNCTION cdi.reject_event_mutation();
 END IF;
END;
$$;
CREATE TABLE IF NOT EXISTS cdi.schema_migrations (
 version INTEGER PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
INSERT INTO cdi.schema_migrations(version) VALUES (1) ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS cdi.browser_sessions (
 sid_hash TEXT PRIMARY KEY, credential_hash TEXT NOT NULL,
 csrf TEXT NOT NULL, expires DOUBLE PRECISION NOT NULL
);
